#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Сверка двух расчётов цикла: числа, кросс-прогоны, пофакторная атрибуция."""
import math
import compare as C

MC_POINT = dict(pi=10.0, T_g=1440.0, N=750e3)
PY_POINT = dict(pi=11.0, T_g=1250.0, N=110e3)


def py(pi, T_g, N, mode='mean', **kw):
    C.CP_MODE = mode
    try:
        return C.python_cycle(pi, T_g=T_g, N=N, **kw)
    finally:
        C.CP_MODE = 'mean'


def hdr(t):
    print('\n' + '=' * 92)
    print(t)
    print('=' * 92)


def main():
    # ---------------- 1. Расчётные точки ----------------
    hdr('1. КАЖДЫЙ РАСЧЁТ В СВОЕЙ ТОЧКЕ')
    mc10 = C.mathcad_cycle(10.0)
    py11 = py(11.0, 1250.0, 110e3)
    rows = [
        ('π*к', f"{10.0:.2f}", f"{11.0:.2f}"),
        ('T*г (перед турбиной), К', f"{1440:.0f}", f"{1250:.0f}"),
        ('N (на валу), кВт', f"{750:.0f}", f"{110:.0f}"),
        ('T*к, К', f"{mc10['T_k']:.1f}", f"{py11['T_k']:.1f}"),
        ('L_к, кДж/кг', f"{mc10['L_k']/1e3:.1f}", f"{py11['L_k']/1e3:.1f}"),
        ('g_m (топливо/воздух)', f"{mc10['g_m']:.5f}", f"{py11['g_m']:.5f}"),
        ('α (из баланса)', f"{mc10['alpha']:.3f}", f"{py11['alpha']:.3f}"),
        ('g_ут (утечки)', '0.007', '0.0075'),
        ('g_охл (на охлаждение)', '0.05 (задано, НЕ используется)', '0.015 (используется)'),
        ('π*т (суммарная)', f"{mc10['pi_t_gg']*mc10['pi_t_c']:.2f}", f"{py11['pi_t']:.2f}"),
        ('L_т, кДж/кг', f"{(mc10['L_t_gg']+mc10['L_t_s'])/1e3:.1f}", f"{py11['L_t']/1e3:.1f}"),
        ('  в т.ч. ТГГ / СТ', f"{mc10['L_t_gg']/1e3:.1f} / {mc10['L_t_s']/1e3:.1f}", '— (одна турбина)'),
        ('η*т', '0.900 (задано)', f"{py11['eta_t']:.3f} (из η_тп=0.905)"),
        ('T*т, К', f"{mc10['T_t_s']:.1f}", f"{py11['T_t']:.1f}"),
        ('N_в.уд, кДж/кг', f"{mc10['L_val']/1e3:.1f}", f"{py11['N_ud']/1e3:.1f}"),
        ('G_в, кг/с', f"{mc10['G_v']:.3f}", f"{py11['G_v']:.3f}"),
        ('G_т, кг/с', f"{mc10['G_t']:.4f}", f"{py11['g_m']*(1-0.0075-0.015)*py11['G_v']:.4f}"),
        ('C_e, кг/(кВт·ч)', f"{mc10['C_e']:.4f}", f"{py11['C_e']:.4f}"),
        ('η_e', f"{mc10['eta_e']:.4f}", f"{py11['eta_e']:.4f}"),
    ]
    print(f"{'параметр':28s}{'Mathcad (файл)':>30s}{'Turbinis-Cycle':>30s}")
    for a, b, c in rows:
        print(f"{a:28s}{b:>30s}{c:>30s}")

    # ---------------- 2. Кросс-прогоны ----------------
    hdr('2. КРОСС-ПРОГОНЫ: одна и та же точка, две модели')
    print(f"{'модель':22s}{'точка':18s}{'C_e':>10s}{'η_e':>9s}{'G_в':>10s}{'T*т':>9s}")
    for name, f in (('Mathcad-модель', lambda p, T, N: C.mathcad_cycle(p, T_sm=T, N=N)),
                    ('Python-модель', lambda p, T, N: py(p, T, N))):
        for pname, (p, T, N) in (('Mathcad (1440/10)', (10.0, 1440.0, 750e3)),
                                 ('Python (1250/11)', (11.0, 1250.0, 110e3))):
            d = f(p, T, N)
            Ce = d['C_e']
            ee = d['eta_e']
            Gv = d['G_v']
            Tt = d['T_t_s'] if 'T_t_s' in d else d['T_t']
            print(f"{name:22s}{pname:18s}{Ce:10.4f}{ee:9.4f}{Gv:10.3f}{Tt:9.1f}")

    # ---------------- 3. Пофакторная атрибуция ----------------
    hdr('3. АТРИБУЦИЯ: Python-модель в точке Mathcad (1440 К, π=10), '
        'коэффициенты по одному к значениям Mathcad')
    base = py(10.0, 1440.0, 750e3)
    print(f"исходно (Python-модель, её коэффициенты): C_e = {base['C_e']:.4f}, "
          f"η_e = {base['eta_e']:.4f}, G_в = {base['G_v']:.3f}, η*т = {base['eta_t']:.3f}, "
          f"T*т = {base['T_t']:.1f}")
    variants = [
        ('C_p: средние -> истинные (как в Mathcad)', dict(mode='true')),
        ('η_к.политроп 0.86 -> 0.83', dict(eta_k_pol=0.83)),
        ('π_с 1.04 -> 1.005 (σ_вых=0.995)', dict(pi_s=1.0 / 0.995)),
        ('η_г 0.98 -> 0.995', dict(eta_g=0.995)),
        ('σ_г 0.965 -> 0.97', dict(sig_g=0.97)),
        ('σ_вх 0.985 -> 0.98', dict(sig_vh=0.98)),
        ('η_м 0.9925 -> 0.995', dict(eta_m=0.995)),
        ('η_р 0.985 -> 0.99', dict(eta_r=0.99)),
        ('Q_н 43150 -> 43000 кДж/кг', dict(Qn=43000.0)),
        ('g_ут 0.0075 -> 0.007', dict(g_ut=0.007)),
        ('g_охл 0.015 -> 0 (Mathcad её не учитывает)', dict(g_ohl=0.0)),
        ('η*т 0.929 -> 0.900 (задано в Mathcad)', dict(eta_t_override=0.9)),
    ]
    print(f"\n{'что меняем':44s}{'C_e':>9s}{'ΔC_e,%':>9s}{'η_e':>8s}{'ΔG_в,%':>9s}{'T*т':>8s}")
    for name, kw in variants:
        mode = kw.pop('mode', 'mean')
        d = py(10.0, 1440.0, 750e3, mode=mode, **kw)
        mode = 'mean'
        print(f"{name:44s}{d['C_e']:9.4f}{100*(d['C_e']/base['C_e']-1):9.2f}"
              f"{d['eta_e']:8.4f}{100*(d['G_v']/base['G_v']-1):9.2f}{d['T_t']:8.1f}")

    # всё вместе (коэффициенты Mathcad, кроме структуры)
    allkw = dict(eta_k_pol=0.83, pi_s=1.0 / 0.995, eta_g=0.995, sig_g=0.97, sig_vh=0.98,
                 eta_m=0.995, eta_r=0.99, Qn=43000.0, g_ut=0.007, g_ohl=0.0,
                 eta_t_override=0.9)
    dall = py(10.0, 1440.0, 750e3, mode='true', **allkw)
    dmean = py(10.0, 1440.0, 750e3, mode='mean', **allkw)
    print(f"\n{'ВСЕ коэффициенты Mathcad, c_p средние':44s}{dmean['C_e']:9.4f}"
          f"{100*(dmean['C_e']/base['C_e']-1):9.2f}{dmean['eta_e']:8.4f}"
          f"{100*(dmean['G_v']/base['G_v']-1):9.2f}{dmean['T_t']:8.1f}")
    print(f"{'ВСЕ коэффициенты + истинные c_p':44s}{dall['C_e']:9.4f}"
          f"{100*(dall['C_e']/base['C_e']-1):9.2f}{dall['eta_e']:8.4f}"
          f"{100*(dall['G_v']/base['G_v']-1):9.2f}{dall['T_t']:8.1f}")
    print(f"{'Mathcad, та же точка':44s}{mc10['C_e']:9.4f}"
          f"{100*(mc10['C_e']/base['C_e']-1):9.2f}{mc10['eta_e']:8.4f}"
          f"{100*(mc10['G_v']/base['G_v']-1):9.2f}{mc10['T_t_s']:8.1f}")
    print(f"  остаток (структура): ΔC_e = {100*(mc10['C_e']/dall['C_e']-1):+.2f} %, "
          f"Δη_e = {100*(mc10['eta_e']/dall['eta_e']-1):+.2f} %")

    # ---------------- 4. Оптимум по π*к ----------------
    hdr('4. ГДЕ ОПТИМУМ π*к В КАЖДОЙ МОДЕЛИ')
    print('Mathcad-модель (T*г=1440, N=750 кВт):')
    print(f"{'π*к':>6}{'G_в':>9}{'C_e':>9}{'η_e':>9}")
    for p in (7, 8, 9, 10, 11, 12, 14, 16, 18, 20):
        d = C.mathcad_cycle(float(p))
        print(f"{p:>6}{d['G_v']:9.3f}{d['C_e']:9.4f}{d['eta_e']:9.4f}")
    print('\nPython-модель (T*г=1250, N=110 кВт):')
    print(f"{'π*к':>6}{'G_в':>9}{'C_e':>9}{'η_e':>9}")
    for p in (7, 8, 9, 10, 11, 12, 14, 16, 18, 20, 25):
        d = py(float(p), 1250.0, 110e3)
        print(f"{p:>6}{d['G_v']:9.3f}{d['C_e']:9.4f}{d['eta_e']:9.4f}")
    print('\nPython-модель при T*г=1440 (для сравнения с Mathcad):')
    print(f"{'π*к':>6}{'G_в':>9}{'C_e':>9}{'η_e':>9}")
    for p in (7, 8, 9, 10, 11, 12, 14, 16, 18, 20):
        d = py(float(p), 1440.0, 750e3)
        print(f"{p:>6}{d['G_v']:9.3f}{d['C_e']:9.4f}{d['eta_e']:9.4f}")

    # ---------------- 5. Отдельно: что даёт охлаждение ----------------
    hdr('5. ВКЛАД ОХЛАЖДЕНИЯ (Python-модель)')
    for p in (11.0,):
        for g in (0.015, 0.05):
            d = py(p, 1250.0, 110e3, g_ohl=g)
            print(f"π*к={p:g}, g_охл={g:.3f}: G_в={d['G_v']:.4f}, C_e={d['C_e']:.4f}, "
                  f"η_e={d['eta_e']:.4f}")
    for T in (1250.0, 1260.0):
        d = py(11.0, T, 110e3)
        print(f"T*г={T:.0f}: g_охл={d['g_ohl']:.3f}, C_e={d['C_e']:.4f}")


if __name__ == '__main__':
    main()
